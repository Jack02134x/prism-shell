#!/usr/bin/env python3
"""Regenerate common/Icons.qml.

Scans every .qml file (and the Python apps in apps/) for string literals that name a Symbols Nerd Font glyph
("wifi" -> md-wifi, or a full name such as "weather-day_sunny") and writes a
small lookup singleton with just those glyphs.
"""
import json
import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = "/usr/share/fonts/TTF/SymbolsNerdFont-Regular.ttf"

names = {n: cp for cp, n in TTFont(FONT).getBestCmap().items()}

found = {}
# names built at runtime (e.g. "battery_" + level) that never appear as literals
EXTRA = [f"battery_{n}" for n in range(10, 100, 10)] + [f"battery_charging_{n}" for n in range(10, 100, 10)]
for s in EXTRA:
    if "md-" + s in names:
        found[s] = names["md-" + s]

literal = re.compile(r'"([a-z0-9_\-]+)"')
# the QML shell, plus the Python apps in apps/ (they read the same table)
sources = [p for p in ROOT.rglob("*.qml") if p.name != "Icons.qml"] + list((ROOT / "apps").rglob("*.py"))
py_literal = re.compile(r"[\"']([a-z0-9_\-]+)[\"']")
for src in sources:
    if "/.cache/" in str(src):
        continue
    pattern = py_literal if src.suffix == ".py" else literal
    for s in pattern.findall(src.read_text()):
        if "md-" + s in names:
            found[s] = names["md-" + s]
        elif s in names and "-" in s:
            found[s] = names[s]


def js(cp):
    if cp > 0xFFFF:
        cp -= 0x10000
        return "\\u%04X\\u%04X" % (0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF))
    return "\\u%04X" % cp


lines = ",\n".join(f'        "{k}": "{js(v)}"' for k, v in sorted(found.items()))
out = f'''pragma Singleton

import QtQuick
import Quickshell

// Generated by scripts/gen-icons.py - Symbols Nerd Font glyphs used by the shell.
Singleton {{
    readonly property var map: ({{
{lines}
    }})

    function get(name) {{
        return map[name] ?? "";
    }}
}}
'''
(ROOT / "common" / "Icons.qml").write_text(out)
print(f"{len(found)} icons")
if len(sys.argv) > 1:
    print(json.dumps(sorted(found)))
